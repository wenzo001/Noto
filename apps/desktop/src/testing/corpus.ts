/**
 * 门禁自己用的"去注释"。**只此一份实现**，别再在每条判据里手抄一遍。
 *
 * 为什么要单独拎出来（缺口 #74 的根因）：本仓一度有六处门禁各写了一份去注释，
 * 其中几处写成了"跨行非贪婪"那一把而**不锚行首**。那种写法有一个致命的失效形状 ——
 * 一份**值**里偶然出现的块注释开批符号（例如 i18n 的文案里写了 `content: "/*"`，或某个 URL 片段）
 * 会被当成"开批"，一路吃到后面某处的收批符号，**中间整段语料被静默吞掉**：
 * 扫描器看到的文件比盘上小一大截，于是"该扫到的没扫到"不报红、而是**安静地什么都不判**。
 * 2026-10-13 在 `i18n.ts` 上真发生过，一次吞掉 191 行。
 *
 * 规则（顺序要紧）：
 * ① 单行形式（开批与收批在同一行内）认**任意位置** —— 这是绝大多数行内注释的形状；
 * ② 跨行的块注释只认**行首开批** —— 本仓的 CSS/TS 都按行首写文档注释，
 *    所以"行中出现开批却在本行没有收批"这种可疑形状宁可**不剥**：
 *    留着它最坏是多报一条红（看得见、会去查），剥错则是静默变瞎（看不见）。
 * ③ 行注释只认行首（两个斜杠前面必须是行首空白），避免把 URL 这类值里的双斜杠当注释切掉。
 *    ⚠ 这条注释里刻意**不写**任何正则字面量：上一版我在这里写了方括号加星号加双斜杠，
 *    那三个字符连起来正好是块注释的收批符号，于是注释当场被关掉、后面的中文变成代码 ——
 *    `vue-tsc` 报的是 `Invalid character` 与 `Unterminated regular expression`（今天第三次栽在同一族上）。
 */

/** 去掉 CSS / Vue / TS 语料里的注释，返回"扫描器该看到的那份文本"。 */
export function stripComments(text: string): string {
  return text
    .replace(/\/\*[^\n]*?\*\//g, '')
    .replace(/^[ \t]*\/\*[\s\S]*?\*\//gm, '')
    .replace(/^[ \t]*\/\/.*$/gm, '')
    .replace(/<!--[\s\S]*?-->/g, '');
}

/**
 * 一条通用的"别变瞎"守卫：去注释之后的长度不许比原文少太多。
 * 真注释占不了语料的一半；少了这么多就是有东西被整段吞掉，宁可红也要问一句。
 * 阈值放宽到 50% 是为了不把"文件里确实写了大段注释"误判成吞语料 —— 它抓的是**黑洞**，不是风格。
 */
export function assertNotBlackout(where: string, raw: string, stripped: string, floor = 0.5): void {
  if (stripped.length < raw.length * floor) {
    throw new Error(
      `${where}：去注释后只剩 ${(stripped.length / Math.max(1, raw.length) * 100).toFixed(1)}% 的语料（${raw.length} → ${stripped.length} 字节），`
      + '像是某处的块注释开批符号把后面整段吞掉了 —— 这条扫描器现在什么都能"通过"，先修它再谈结论',
    );
  }
}
